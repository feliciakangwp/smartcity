// Writes supabase/seed.sql from the Demo Mode seed so both stay identical.
// Run: npm run gen:seed-sql
import { writeFileSync } from 'node:fs';
import { createSeed } from '../src/data/seed';
import { PORTS } from '../src/data/layout';

const d = createSeed();
class UuidArray {
  constructor(public ids: string[]) {}
}
const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (v instanceof UuidArray) return `array[${v.ids.map(q).join(', ')}]::uuid[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table: string, rows: Record<string, unknown>[]) =>
  rows.length
    ? `insert into public.${table} (${Object.keys(rows[0]).join(', ')}) values\n` +
      rows.map((r) => `  (${Object.values(r).map(q).join(', ')})`).join(',\n') +
      ';\n'
    : '';

let sql = '-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.\n-- Demo data: agency systems on a Singapore layout. Years originated, eCustoms module names/usage and the example data flows are placeholders.\n\n';
sql += insert('zone_plots', d.plots.map((p) => ({ id: p.id, label: p.label, x: p.x, z: p.z, width: p.width, depth: p.depth, ring: p.ring })));
sql += insert('zones', d.zones.map((z) => ({ id: z.id, name: z.name, description: z.description, color: z.color, theme: z.theme, kind: z.kind, plot_id: z.plotId, scale: z.scale, visible: z.visible, sort_order: z.sortOrder })));
sql += insert('systems', d.systems.map((s) => ({
  id: s.id, name: s.name, acronym: s.acronym, description: s.description, display_zone_id: s.zoneId, owning_zone_id: s.owningZoneId, business_purpose: s.businessPurpose,
  category: s.category, status: s.status, criticality: s.criticality, tech_stack: s.techStack ?? null, owner: s.owner ?? null,
  endpoints: s.endpoints ?? null, docs: s.docs, year_introduced: s.yearIntroduced ?? null, build_progress: s.buildProgress ?? null,
  product_team: s.productTeam || null, year_originated: s.yearOriginated ?? null, decommission_year: s.decommissionYear ?? null,
})));
sql += insert('system_revamps', d.systems.flatMap((s) => (s.revamps ?? []).map((r) => ({ id: r.id, system_id: s.id, year: r.year, areas: r.areas, use_for_age: r.useForAge }))));
sql += insert('system_data_inputs', d.systems.flatMap((s) => (s.inputs ?? []).map((i) => ({ id: i.id, system_id: s.id, data: i.data, from_system_id: i.fromSystemId }))));
sql += insert('system_data_outputs', d.systems.flatMap((s) => (s.outputs ?? []).map((o) => ({ id: o.id, system_id: s.id, data: o.data, to_system_id: o.toSystemId }))));
sql += insert('system_modules', d.systems.flatMap((s) => (s.modules ?? []).map((m, i) => ({ id: m.id, system_id: s.id, name: m.name, sort_order: i }))));
sql += insert('system_module_usage', d.systems.flatMap((s) => (s.modules ?? []).flatMap((m) => m.usingZoneIds.map((z) => ({ module_id: m.id, zone_id: z })))));
sql += insert('system_division_usage', d.systems.flatMap((s) => s.usingZoneIds.map((z) => ({ system_id: s.id, zone_id: z }))));
sql += insert('integrations', d.integrations.map((i) => ({
  id: i.id, name: i.name, source_id: i.sourceId, destination_id: i.destinationId, data_type: i.dataType, mechanism: i.mechanism,
  direction: i.direction, description: i.description, trigger_event: i.trigger, status: i.status, via: new UuidArray(i.via), payload: i.payload ?? null,
})));
sql += insert('journeys', d.journeys.map((j) => ({ id: j.id, code: j.code, name: j.name, description: j.description, published: j.published, speed: j.speed })));
sql += insert('journey_steps', d.journeys.flatMap((j) => j.steps.map((s) => ({ id: s.id, journey_id: j.id, step_order: s.order, integration_id: s.integrationId, label: s.label }))));
sql += insert('journey_branches', d.journeys.flatMap((j) => j.branches.map((b) => ({ id: b.id, journey_id: j.id, after_step_id: b.afterStepId, condition: b.condition, integration_id: b.integrationId }))));
sql += insert('berths', d.berths.map((b) => ({ id: b.id, name: b.name, port_id: b.portId, x: b.x })));
sql += insert('ships', d.ships.map((s) => ({
  id: s.id, name: s.name, port_id: s.portId, hull_color: s.hullColor, bays: s.bays, row_count: s.rows, tiers: s.tiers,
  unload_count: s.unloadCount, load_count: s.loadCount, sea_time_seconds: s.seaTime,
})));
sql += insert('shipping_routes', PORTS.flatMap((p) => [
  { name: `${p.name} approach`, kind: 'entry', waypoints: p.entry },
  { name: `${p.name} departure`, kind: 'exit', waypoints: p.exit },
  { name: `${p.name} anchorage`, kind: 'anchorage', waypoints: p.anchorages },
]));
sql += `insert into public.simulation_settings (id, ambient_enabled, default_speed) values (true, ${d.simulation.ambientEnabled}, ${d.simulation.defaultSpeed});\n`;
sql += `insert into public.dashboard_settings (id, platform_name, tagline, quality, map_rings) values (true, ${q(d.platform.name)}, ${q(d.platform.tagline)}, ${q(d.platform.quality)}, ${d.platform.mapRings});\n`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('Wrote supabase/seed.sql');
